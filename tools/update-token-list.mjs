/**
 * Regenerate packages/chain/src/token-list.ts from Uniswap's default token list.
 *
 *   node tools/update-token-list.mjs [<commit>]
 *
 * The token check knows three assets by name — USDT, USDC and WBTC — and a fake with any other
 * ticker could only be caught by its records. This list is the second, weaker tier: about four
 * hundred tokens somebody else curated, so a fake `DAI` or `cbBTC` is at least questioned by name.
 * How the tiers are weighed is `inspectToken`'s business, in packages/engine/src/tokens.ts.
 *
 * Pinned to a commit and written into the repository rather than fetched at run time: the app
 * should not depend on a third party being up to judge a token, and a list that moves underneath
 * a measurement makes the measurement unrepeatable. With no argument, the list's current head is
 * resolved and recorded.
 */

import {execFileSync} from "node:child_process";
import {writeFileSync} from "node:fs";
import {dirname, join} from "node:path";
import {fileURLToPath} from "node:url";

const REPO = "https://github.com/Uniswap/default-token-list";
const commit =
  process.argv[2] ??
  execFileSync("git", ["ls-remote", REPO, "HEAD"], {encoding: "utf8"}).split(/\s/)[0];
if (!/^[0-9a-f]{40}$/.test(commit)) throw new Error(`not a commit: ${commit}`);

// curl rather than fetch, as in analysis/src/token-precision.mjs: on the machine this was written
// on, Node's fetch could not reach raw.githubusercontent.com when curl could.
const url = `https://raw.githubusercontent.com/Uniswap/default-token-list/${commit}/src/tokens/mainnet.json`;
const tokens = JSON.parse(execFileSync("curl", ["-s", "-m", "60", "-L", url], {encoding: "utf8"}));

const rows = tokens
  .filter((t) => t.chainId === 1 && /^0x[0-9a-fA-F]{40}$/.test(t.address) && typeof t.symbol === "string")
  .map((t) => ({symbol: t.symbol, address: t.address}))
  .sort((a, b) => a.symbol.localeCompare(b.symbol, "en") || a.address.localeCompare(b.address));
if (rows.length < 100) throw new Error(`only ${rows.length} tokens at ${commit}; refusing to write a list that thin`);

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "packages", "chain", "src", "token-list.ts");
writeFileSync(
  out,
  `// Generated by tools/update-token-list.mjs from Uniswap's default token list. Do not edit by hand:
// rerun the script, which records the commit it read.

import type {CanonicalToken} from "@truesend/engine";

export const LISTED_TOKENS_SOURCE = {
  list: "Uniswap default token list",
  url: ${JSON.stringify(`${REPO}/blob/${commit}/src/tokens/mainnet.json`)},
  commit: ${JSON.stringify(commit)},
  tokens: ${rows.length},
} as const;

/**
 * Tokens that are what they say they are, by somebody else's curation, per chain id.
 *
 * The token check's second tier: a token named like one of these at a different contract is
 * questioned, and called counterfeit only once it has been used against the account — tickers are
 * not unique, and this list is long enough that a legitimate project shares one now and then.
 */
export const LISTED_TOKENS: Partial<Record<number, readonly CanonicalToken[]>> = {
  1: [
${rows.map((r) => `    {symbol: ${JSON.stringify(r.symbol)}, address: ${JSON.stringify(r.address)}},`).join("\n")}
  ],
};
`,
);
console.log(`wrote ${rows.length} tokens from ${commit.slice(0, 7)} to packages/chain/src/token-list.ts`);
